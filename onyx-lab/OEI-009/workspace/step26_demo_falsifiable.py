        f"与 case-management-consulting、methodology-framework、\n"
        f"play-sales-delivery 三份演示文档同处一个主题带，因此以 marker 为\n"
        f"query 时可与之一起被召回，用于验证“同一 query、不同身份”的过滤。\n\n"
