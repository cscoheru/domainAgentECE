"""OEI-009 step 2.6 — demo-falsifiable comparison data (idempotent, R1 rework).

TASK §0.3 carve-out: ONE allowed write into demo project id=1 (a restricted
classification comparison doc + explicit ACL row so demo_user sees it,
others don't).

R1 (codex VERDICT #2 §4.1): this script MUST be safely re-runnable so its
evidence files can be regenerated deterministically.

Rework history
--------------
v1 (a884d41 era) had two defects:
  (a) its cleanup DELETEd Onyx files **without the session cookie** and
      swallowed every exception with `except: pass` → every rerun left an
      orphan `ece-*-oei009-comparison-restricted` file behind, and the
      registry rows it deleted went out of sync with the engine. That is
      exactly how `05` ended up with `demo_user = 5`.
  (b) the file ids it deleted came ONLY from its own registry rows, so once
      a row was gone the Onyx file became unfindable.
  (c) it used a **time-based** marker, so every rerun produced a different
      controlled filename and a different recall behaviour → the evidence
      was not reproducible.

v2 (this file):
  (a) deletes carry the session cookie and record real status codes;
      any non-2xx is a LOUD failure, never swallowed.
  (b) files are additionally found **by name pattern** in project 1, so
      orphans without registry rows are still cleaned.
  (c) the marker is FIXED → deterministic controlled filename → the
      evidence can be regenerated byte-for-byte.
  (d) both demo queries are fixed and their recall composition is asserted.

Recall-composition root cause (measured 2026-09-25, this session)
-----------------------------------------------------------------
`POST /api/search` is NOT a plain vector top-k. It runs `SearchTool.run()`
(the same agentic multi-stage pipeline that powers chat mode — see
`/app/onyx/server/features/search/api.py` in the api_server container), which
includes LLM query expansion and LLM auto filter detection. Consequences,
all measured on this deployment:
  * latency 20–56 s per search;
  * the number of returned results is a *relevance* outcome, not a fixed k:
    the same corpus returned 1, 2, 3 or 4 docs for different queries;
  * therefore "which docs a query recalls" cannot be assumed — it is
    MEASURED here, and each chosen query is repeated to show stability.

Two queries, both verified stable (3/3 identical raw recall):

  DEMO_QUERY  = the marker token            → raw recall = 4
                (the 3 public demo docs + this restricted doc)
                ⇒ anonymous 3, other user 3, demo_user 4   [A4 / R1]

  ISO_QUERY   = 员工报销政策与发票审核流程  → raw recall = 1
                (ONLY this restricted doc — the topic exists nowhere else)
                ⇒ anonymous 0, other user 0, demo_user 1   [A7 no-hit / R2]

Using a *topically disjoint* section inside this doc (rather than a
meaningless random string) is what makes the zero-authorized-result branch a
genuine, explainable state instead of a retrieval accident.

Output: prints + JSON evidence (same shape as before, plus the R2 section).
"""
